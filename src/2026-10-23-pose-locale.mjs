const CATEGORIES=Object.freeze({action:'동작',move:'이동',lie:'눕기',stand:'서기',sit:'앉기'});
export function poseLabel(pose){return LABELS[pose?.id]??pose?.name??'알 수 없는 자세';}
export function poseCategory(pose){return CATEGORIES[pose?.category]??'기타';}
const normalize=value=>String(value??'').normalize('NFKC').toLocaleLowerCase().replace(/\s+/gu,' ').trim();
export function matchesPose(pose,query){
  const haystack=normalize([pose?.id,pose?.name,pose?.category,poseLabel(pose),poseCategory(pose)].join(' '));
  return normalize(query).split(' ').every(token=>haystack.includes(token));
}
